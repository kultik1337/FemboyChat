-- Альбомы: несколько медиа, отправленных одним махом.
--
-- Почему колонка, а не массив вложений в одном ряду:
--
-- Ряд `messages` уже несёт реакции, ответ, закрепление, просмотры, TTL и
-- собственное удаление. Сложи пять фотографий в один ряд — и всё это станет
-- общим на пять картинок сразу: нельзя ответить на третью, нельзя удалить
-- только её, реакция ставится на набор. Телеграм по той же причине держит
-- альбом как отдельные сообщения с общим `grouped_id`, а склеивает их
-- клиент при отрисовке.
--
-- Так правка схемы сводится к одной необязательной колонке, а старые клиенты,
-- которые про альбомы не знают, покажут те же сообщения по одному — то есть
-- ровно то, чем альбом и является на самом деле.
--
-- Идентификатор генерирует клиент (обычный rid()), поэтому тип text, а не
-- uuid: значение непрозрачно для базы и ни с чем не связано внешним ключом.
alter table public.messages
  add column if not exists album_id text;

comment on column public.messages.album_id is
  'Общий идентификатор альбома. Сообщения с одним значением клиент рисует одной сеткой; подпись и ответ живут на самом раннем из них. NULL — обычное одиночное сообщение.';

-- Индекса здесь намеренно нет.
--
-- Альбом никогда не ищут запросом: страница истории и так приходит целиком, а
-- склейка идёт в памяти по уже загруженным сообщениям. Индекс на колонку,
-- которая не участвует ни в одном where, — это только замедление вставки и
-- ещё одна строка в отчёте линтера про неиспользуемые индексы (их там уже
-- тринадцать).
