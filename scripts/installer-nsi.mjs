/*
  Собственный сценарий установщика (NSIS).

  Стандартный шаблон Tauri — это MUI2: серая шапка, рамка, четыре
  страницы и кнопки внизу. Как его ни крась картинками, это остаётся
  мастером из девяностых. Здесь шаблон собирается целиком свой: вся
  стандартная обвязка прячется, диалог растягивается на всё окно, фон — наша
  картинка, кнопки нарисованы сами: один экран, одна кнопка, прогресс,
  автозапуск — как у современных мессенджеров.

  Почему генератор, а не готовый .nsi в репозитории: все пути внутри
  абсолютные, а версия берётся из package.json. Так сценарий не зависит от
  того, в какую временную папку Tauri его положит перед сборкой, и версия
  никогда не расходится с остальным проектом.

  В тексте сценария море конструкций вида ${If}, поэтому он собран из
  массива обычных строк, а не шаблонной строки: иначе JS попытается
  подставить туда свои переменные.
*/

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8'))
const version = pkg.version

const outDir = resolve(root, 'src-tauri', 'installer')
const bundleDir = resolve(root, 'src-tauri', 'target', 'release', 'bundle', 'nsis')

const paths = {
  out: resolve(bundleDir, `FemboyChat_${version}_x64-setup.exe`),
  icon: resolve(root, 'src-tauri', 'icons', 'icon.ico'),
  bg: resolve(outDir, 'bg.bmp'),
  exe: resolve(root, 'src-tauri', 'target', 'release', 'femboychat.exe'),
}

