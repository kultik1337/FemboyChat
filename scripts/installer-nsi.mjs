  'InstallDir "$LOCALAPPDATA\\FemboyChat"',
  'InstallDirRegKey HKCU "Software\\FemboyChat" "InstallDir"',
  'RequestExecutionLevel user',
  'SetCompressor /SOLID lzma',
  'XPStyle on',
